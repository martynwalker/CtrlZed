using System.Globalization;
using System.Text.RegularExpressions;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Documents;
using System.Windows.Media;
using System.Windows.Media.Imaging;

namespace CtrlZed;

public sealed record AiResultPart(string? Text,BitmapSource? Image);

public static class AiResultRenderer
{
    static readonly Regex ChartRegex=new(
        @"\[CTRLZED_CHART\](.*?)\[/CTRLZED_CHART\]",
        RegexOptions.IgnoreCase|RegexOptions.Singleline|RegexOptions.Compiled);

    public static IReadOnlyList<AiResultPart> Parse(string result)
    {
        var parts=new List<AiResultPart>();
        var pos=0;
        foreach(Match match in ChartRegex.Matches(result??""))
        {
            if(match.Index>pos)
                parts.Add(new AiResultPart((result??"")[pos..match.Index].Trim(),null));

            var chart=TryRenderChart(match.Groups[1].Value);
            if(chart!=null)parts.Add(new AiResultPart(null,chart));
            else parts.Add(new AiResultPart(match.Value,null));
            pos=match.Index+match.Length;
        }

        if(pos<(result?.Length??0))
            parts.Add(new AiResultPart(result![pos..].Trim(),null));

        if(parts.Count==0&& !string.IsNullOrWhiteSpace(result))
            parts.Add(new AiResultPart(result.Trim(),null));
        return parts;
    }

    public static BitmapSource? TryRenderChart(string body)
    {
        var lines=body.Replace("\r\n","\n").Split('\n',StringSplitOptions.RemoveEmptyEntries)
            .Select(x=>x.Trim()).Where(x=>x.Length>0).ToList();
        if(lines.Count<2)return null;

        var title="AI comparison";
        if(lines[0].StartsWith("TITLE:",StringComparison.OrdinalIgnoreCase))
        {
            title=lines[0][6..].Trim();
            lines.RemoveAt(0);
        }

        var data=new List<(string Label,double Value)>();
        foreach(var line in lines)
        {
            var p=line.LastIndexOf('|');
            if(p<=0)continue;
            var label=line[..p].Trim();
            var raw=line[(p+1)..].Trim().TrimEnd('%');
            if(double.TryParse(raw,NumberStyles.Float,CultureInfo.InvariantCulture,out var value))
                data.Add((label,value));
        }
        if(data.Count==0)return null;

        const int width=900;
        const int height=520;
        var dv=new DrawingVisual();
        using(var dc=dv.RenderOpen())
        {
            dc.DrawRectangle(Brushes.White,null,new Rect(0,0,width,height));
            var titleText=new FormattedText(title,CultureInfo.CurrentCulture,FlowDirection.LeftToRight,
                new Typeface("Segoe UI"),24,Brushes.Black,1.0);
            dc.DrawText(titleText,new Point(35,20));

            var left=190d;var right=40d;var top=80d;var bottom=55d;
            var plotW=width-left-right;var plotH=height-top-bottom;
            var max=Math.Max(1,data.Max(x=>Math.Abs(x.Value)));
            var zero=left+plotW/2;
            var axisPen=new Pen(Brushes.Gray,1);
            dc.DrawLine(axisPen,new Point(zero,top),new Point(zero,top+plotH));

            var rowH=plotH/data.Count;
            for(int i=0;i<data.Count;i++)
            {
                var y=top+i*rowH+rowH*0.18;
                var barH=rowH*0.58;
                var labelText=new FormattedText(data[i].Label,CultureInfo.CurrentCulture,FlowDirection.LeftToRight,
                    new Typeface("Segoe UI"),15,Brushes.Black,1.0){MaxTextWidth=left-20,Trimming=TextTrimming.CharacterEllipsis};
                dc.DrawText(labelText,new Point(15,y+Math.Max(0,(barH-labelText.Height)/2)));

                var half=plotW/2-10;
                var len=Math.Min(half,Math.Abs(data[i].Value)/max*half);
                var x=data[i].Value>=0?zero:zero-len;
                var brush=data[i].Value>=0
                    ?new SolidColorBrush(Branding.Gold)
                    :new SolidColorBrush(Color.FromRgb(92,121,158));
                dc.DrawRoundedRectangle(brush,null,new Rect(x,y,len,barH),3,3);

                var value=$"{data[i].Value:+0.##;-0.##;0}%";
                var vt=new FormattedText(value,CultureInfo.InvariantCulture,FlowDirection.LeftToRight,
                    new Typeface("Segoe UI Semibold"),14,Brushes.Black,1.0);
                var vx=data[i].Value>=0?Math.Min(width-right-vt.Width,zero+len+7):Math.Max(left,zero-len-vt.Width-7);
                dc.DrawText(vt,new Point(vx,y+(barH-vt.Height)/2));
            }

            var note=new FormattedText("Generated by CtrlZed from AI-supplied comparison data",
                CultureInfo.CurrentCulture,FlowDirection.LeftToRight,new Typeface("Segoe UI"),11,Brushes.DimGray,1.0);
            dc.DrawText(note,new Point(width-note.Width-25,height-30));
        }

        var bitmap=new RenderTargetBitmap(width,height,96,96,PixelFormats.Pbgra32);
        bitmap.Render(dv);
        bitmap.Freeze();
        return bitmap;
    }

    public static string DocumentPrompt(string instruction,string selectedText,string documentText,bool allowChart)
    {
        var context=string.IsNullOrWhiteSpace(selectedText)
            ?"No text is selected. The request applies at the current insertion point."
            :$"Selected text:\n---\n{selectedText}\n---";

        var chartRules=allowChart
            ?@"If a useful comparison chart is requested, include exactly this plain-text block in addition to the prose:
[CTRLZED_CHART]
TITLE: Short chart title
Label 1|12.4
Label 2|-3.8
[/CTRLZED_CHART]
Values must be numeric percentages. Do not put the chart block inside Markdown fences."
            :"Do not emit chart blocks.";

        return
$@"You are the writing and research assistant inside CtrlZed, a Windows word processor.
Produce finished document content, not commentary about how you would produce it.

User request:
{instruction}

{context}

Whole-document context, when useful:
---
{TrimContext(documentText,30000)}
---

{chartRules}

Use British English unless the user asks otherwise.
For current or time-sensitive requests, use live web/search capability when available and make dates explicit.
Return only the material suitable for insertion into the document.";
    }

    public static string MacroPrompt(string instruction,string macroReference,string existingCode)
    {
        var extended=macroReference.Contains("EXTENDED MACROS ARE ENABLED",StringComparison.OrdinalIgnoreCase);
        var mode=extended
            ?@"You are writing an EXTENDED CtrlZed .czm macro. Extended macro mode is enabled in the application.
The command reference below is authoritative. PROMPT and INSERT_QR are implemented capabilities when they appear in that reference.
Do not claim that interactive prompts, QR generation or image insertion are unavailable if PROMPT or INSERT_QR are listed."
            :@"You are writing a SAFE CtrlZed .czm macro using only the restricted command language below.";

        return
$@"{mode}

User request:
{instruction}

Current macro editor content, if any:
---
{existingCode}
---

Supported CtrlZed macro language for the CURRENT mode:
{macroReference}

Return ONLY the complete .czm source. Comments may begin with #.
Do not return Markdown fences, C#, VB.NET, PowerShell, shell commands, filesystem/network/process operations, or commands absent from the supplied reference.
Treat every command explicitly listed in the reference as implemented and available.
Only return an unsupported-capability explanation when the required capability is genuinely absent from the supplied reference.";
    }

    static string TrimContext(string text,int max)
    {
        if(string.IsNullOrEmpty(text))return "";
        return text.Length<=max?text:text[..max]+"\n[document context truncated]";
    }
}
